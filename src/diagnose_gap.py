"""Diagnose: HVOR taber Poisson-modellen log loss til markedet?

Pr. kamp: d = logloss(model) - logloss(marked) for det faktiske resultat (d > 0 = markedet bedst).
Opdelt efter uenighed, retning, favoritstyrke og sæsonfase. Genbruger backtest() fra
backtest_market.py (J1, alle sæsoner) og backtest_j2_market.py (J2 2022-2024).

Skriver selv reports/diagnose_gap.md og reports/diagnose_gap.png – ingen tal tastet i hånden.

Kør:  uv run python src/diagnose_gap.py
"""
import math
from datetime import datetime, timezone

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

import backtest_j2_market
import backtest_market
from backtest_market import OUTCOMES

K_DIAG = 12
REPORT_MD = "reports/diagnose_gap.md"
REPORT_PNG = "reports/diagnose_gap.png"

DISAGREE_BINS = [0, 5, 10, 15, np.inf]
DISAGREE_LABELS = ["<5 pp", "5–10 pp", "10–15 pp", ">15 pp"]
DIRECTION_BINS = [-np.inf, -10, -5, 0, 5, np.inf]
DIRECTION_LABELS = ["< −10 pp (model on underdog)", "−10 to −5 pp", "−5 to 0 pp",
                    "0 to +5 pp", "> +5 pp (model on favourite)"]
FAV_BINS = [0, 45, 55, 65, 100]
FAV_LABELS = ["<45 %", "45–55 %", "55–65 %", ">65 %"]
PHASE_LABELS = ["Q1 (start)", "Q2", "Q3", "Q4 (end)"]


def per_match(bt):
    """Tilføj d og opdelingsvariable til en backtest-tabel."""
    bt = bt.copy()
    p_act = bt.apply(lambda r: r["p" + r["result"]], axis=1)
    m_act = bt.apply(lambda r: r["m" + r["result"]], axis=1)
    bt["d"] = -np.log(p_act) + np.log(m_act)

    p = bt[["p" + o for o in OUTCOMES]].to_numpy()
    m = bt[["m" + o for o in OUTCOMES]].to_numpy()
    bt["disagree"] = np.abs(p - m).max(axis=1) * 100

    fav = np.where(m[:, 0] >= m[:, 2], 0, 2)             # markedets favorit: hjemme eller ude (aldrig X)
    rows = np.arange(len(bt))
    bt["fav"] = [OUTCOMES[i] for i in fav]
    bt["p_fav"], bt["m_fav"] = p[rows, fav], m[rows, fav]
    bt["direction"] = (bt.p_fav - bt.m_fav) * 100
    bt["fav_won"] = bt.result == bt.fav

    # Sæsonfase: kvartiler af dato inden for sæsonen (kampe samme dag i samme kvartil)
    dates = pd.to_datetime(bt["date"])
    rank = dates.groupby(bt["season"]).rank(method="min", pct=True)
    bt["phase"] = pd.cut(rank, [0, 0.25, 0.5, 0.75, 1], labels=PHASE_LABELS)

    bt["disagree_bin"] = pd.cut(bt.disagree, DISAGREE_BINS, labels=DISAGREE_LABELS, right=False)
    bt["direction_bin"] = pd.cut(bt.direction, DIRECTION_BINS, labels=DIRECTION_LABELS, right=False)
    bt["fav_bin"] = pd.cut(bt.m_fav * 100, FAV_BINS, labels=FAV_LABELS, right=False)
    return bt


def split(bt, col):
    total = bt.d.sum()
    g = bt.groupby(col, observed=False).d
    out = pd.DataFrame({"n": g.size(), "mean_d": g.mean(), "se": g.std() / np.sqrt(g.size()),
                        "share": g.sum() / total})
    return out


def md_split(title, tables):
    lines = [f"### {title}", "",
             "| Bin | League | n | Mean d | ± 1 SE | Share of total gap |",
             "|---|---|---:|---:|---:|---:|"]
    for league, t in tables.items():
        for label, r in t.iterrows():
            se = "–" if math.isnan(r.se) else f"{r.se:.4f}"
            mean = "–" if math.isnan(r.mean_d) else f"{r.mean_d + 0.0:+.4f}"
            lines.append(f"| {label} | {league} | {int(r.n)} | {mean} | {se} | {round(r.share, 2) + 0.0:.0%} |")
    return lines + [""]


def plot(tables):
    colors = {"J1": "#2a78d6", "J2": "#eb6834"}            # kategoriske slots 1-2
    x = np.arange(len(DISAGREE_LABELS))
    fig, ax = plt.subplots(figsize=(7, 4.2))
    for i, (league, t) in enumerate(tables.items()):
        off = (i - 0.5) * 0.12
        ax.errorbar(x + off, t.mean_d, yerr=t.se, fmt="o", ms=7, capsize=4, lw=2,
                    color=colors[league], label=f"{league} (n = {int(t.n.sum())})")
    ax.axhline(0, color="#52514e", lw=1)
    ax.set_xticks(x, DISAGREE_LABELS)
    ax.set_xlabel("Disagreement: max |p_model − p_market| over H/D/A")
    ax.set_ylabel("Mean d = logloss(model) − logloss(market)")
    ax.set_title("Where the model loses log loss to the market (±1 SE)", loc="left")
    for s in ["top", "right"]:
        ax.spines[s].set_visible(False)
    ax.grid(axis="y", color="#e6e5e0", lw=0.8)
    ax.set_axisbelow(True)
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(REPORT_PNG, dpi=150)
    plt.close(fig)


def main():
    leagues = {
        "J1": pd.concat([backtest_market.backtest(s, K_DIAG) for s in range(2012, 2027)],
                        ignore_index=True),
        "J2": pd.concat([backtest_j2_market.backtest(s, K_DIAG) for s in [2022, 2023, 2024]],
                        ignore_index=True),
    }
    leagues = {k: per_match(v) for k, v in leagues.items()}

    md = ["# Where does the model lose log loss to the market?",
          f"_Generated by `src/diagnose_gap.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC, "
          f"k = {K_DIAG}._", "",
          "Per match: **d = logloss(model) − logloss(market)** for the actual result. "
          "d > 0 means the market was better. *Share of total gap* = sum of d in the bin / sum of d "
          "over all matches (can be negative, or above 100 %).", "",
          "J1: all seasons, Pinnacle closing odds (average odds when Pinnacle is missing). "
          "J2: 2022–2024, CheckBestOdds (a weaker benchmark).", "",
          "## Total gap", "",
          "| League | n | Mean d | ± 1 SE | Log loss model | Log loss market |",
          "|---|---:|---:|---:|---:|---:|"]
    for league, bt in leagues.items():
        md.append(f"| {league} | {len(bt)} | {bt.d.mean():+.4f} | {bt.d.std() / math.sqrt(len(bt)):.4f} "
                  f"| {backtest_market.logloss(bt, 'p'):.4f} | {backtest_market.logloss(bt, 'm'):.4f} |")
    md.append("")

    md += ["## Calibration on favourite and draw", "",
           "Market favourite = home or away, whichever has the higher no-vig market probability "
           "(the draw is never the favourite; ties go to home).", "",
           "| League | Event | Actual | Model (mean) | Market (mean) |",
           "|---|---|---:|---:|---:|"]
    for league, bt in leagues.items():
        md.append(f"| {league} | Favourite wins | {bt.fav_won.mean():.1%} | {bt.p_fav.mean():.1%} "
                  f"| {bt.m_fav.mean():.1%} |")
        md.append(f"| {league} | Draw | {(bt.result == 'X').mean():.1%} | {bt.pX.mean():.1%} "
                  f"| {bt.mX.mean():.1%} |")
    md.append("")

    md += ["## Splits", ""]
    disagree = {lg: split(bt, "disagree_bin") for lg, bt in leagues.items()}
    md += md_split("1. Disagreement size: max |p_model − p_market| over H/D/A", disagree)
    for league, bt in leagues.items():                   # samlet andel for de to store uenigheds-bins
        big = bt.disagree >= 10
        md.append(f"- **{league}, disagreement ≥ 10 pp combined:** {big.mean():.0%} of matches, "
                  f"{bt.d[big].sum() / bt.d.sum():.0%} of the total gap")
    md += ["", "![Mean d by disagreement bin](diagnose_gap.png)", ""]
    md += md_split("2. Direction: model's probability for the market favourite minus the market's",
                   {lg: split(bt, "direction_bin") for lg, bt in leagues.items()})
    md += md_split("3. Market favourite strength (no-vig market probability of the favourite)",
                   {lg: split(bt, "fav_bin") for lg, bt in leagues.items()})
    md += md_split("4. Season phase: quartiles of match date within each season",
                   {lg: split(bt, "phase") for lg, bt in leagues.items()})

    plot(disagree)
    with open(REPORT_MD, "w") as f:
        f.write("\n".join(md))
    print(f"Wrote {REPORT_MD} and {REPORT_PNG}")
    for league, bt in leagues.items():
        print(f"  {league}: n = {len(bt)}, mean d = {bt.d.mean():+.4f}")


if __name__ == "__main__":
    main()
